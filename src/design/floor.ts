/**
 * Tailwind's `text-xs` is 0.75rem — 12px, under the floor. The other named
 * steps (`text-sm` at 14px and up) are fine, and there is no `text-2xs`.
 */
const TAILWIND_NAMED_BELOW_FLOOR = /\btext-xs\b/g

/**
 * `text-[10px]`, `text-[0.65rem]`, and the `text-[length:11px]` type hint.
 * Arbitrary values, which is where most are.
 */
const ARBITRARY_SIZE = /\btext-\[(?:length:)?(\d*\.?\d+)(px|rem)\]/g

/** A raw declaration in a stylesheet: `font-size: 0.725rem`. */
const CSS_FONT_SIZE = /font-size:\s*(\d*\.?\d+)(px|rem)/g

/**
 * The `font:` shorthand, where the size follows an optional style and weight:
 * `font: 600 11px/1 sans-serif`. `font: inherit` has no length and is skipped.
 */
const CSS_FONT_SHORTHAND = /\bfont:\s*(?:[^;\n}'"]*?\s)?(\d*\.?\d+)(px|rem)/g

/**
 * A JSX style object: `fontSize: '11px'`, or a bare number, which React reads
 * as px. The lookahead keeps `'1.5em'` from matching as a bare `1`.
 */
const JSX_FONT_SIZE = /\bfontSize:\s*['"`]?(\d*\.?\d+)(px|rem)?(?![\w.%])/g

/**
 * Deliberately not matching `em`: it resolves against the parent, so 0.75em is
 * only a violation depending on where it lands, and a guard that guesses is a
 * guard that gets muted. There are none in this repo; if one appears, the
 * reviewer catches it.
 */
function toPx(value: string, unit: string | undefined): number {
  return unit === 'rem' ? Number(value) * 16 : Number(value)
}

/**
 * The `font-mono` utility, any hand-rolled read of the variable, and the mono
 * stacks CLAUDE.md's audit grep lists: `ui-monospace`, `monospace` and
 * `Noto Sans Mono`. `ui-monospace` is one match, not two.
 */
const MONO = /\bfont-mono\b|var\(--font-mono\)|\b(?:ui-)?monospace\b|\bNoto Sans Mono\b/g

const HUES =
  'slate|gray|zinc|neutral|stone|red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose'

/**
 * A Tailwind default palette colour on any utility that takes one. Matches the
 * full `<utility>-<hue>-<step>` shape so that prose, a variable named `slate`,
 * or one of our own tokens cannot trip it. A side or offset segment may sit
 * between utility and hue (`border-t-red-500`, `ring-offset-green-500`), and
 * the palette's own variable may be read directly (`var(--color-sky-300)`).
 */
const PALETTE = new RegExp(
  `\\b(?:bg|text|border|ring|from|to|via|shadow|fill|stroke|outline|decoration|accent|caret|divide|placeholder)(?:-(?:[trblxyse]|offset))?-(?:${HUES})-\\d{2,3}\\b` +
    `|var\\(--color-(?:${HUES})-\\d{2,3}\\)`,
  'g',
)

/**
 * The seven rules that were DESIGN.md's audit greps, so `/design-sync` runs as a
 * test instead of as something a person remembers.
 *
 * `hex`: a colour written as a hex literal, in a component or a route. Scoped
 * to `src/components` and `src/app` as the grep was; the token source and
 * `lib/camera/color.ts` compute colour and are out of scope. DESIGN.md names
 * the files that may carry one (Satori ignores `oklch()`; the web manifest and
 * `themeColor` are read by the OS; Google's mark is Google's), and those are
 * the only exceptions — by filename or by the symbol DESIGN.md names, never by
 * a per-line escape. `&#123;` is an HTML entity, not a colour.
 */
const HEX = /(?<![&\w])#(?:[0-9a-f]{8}|[0-9a-f]{6}|[0-9a-f]{4}|[0-9a-f]{3})(?![\w-])/gi
const HEX_SCOPE = /^src\/(components|app)\//
/**
 * By basename, as DESIGN.md's grep matches them: a metadata route keeps its
 * name at any depth (`[locale]/recipe/[slug]/opengraph-image.tsx`), and a
 * full-path list missed exactly that one.
 */
const HEX_FILES = /^src\/app\/(?:.+\/)?(?:icon\.tsx|opengraph-image\.tsx|manifest\.ts)$/
const HEX_LINE = /\bthemeColor\b/
/** The component whose body is Google's colours, not ours. */
const HEX_COMPONENTS = new Set(['GoogleMark'])

/**
 * A stroke doing elevation's job (rule 4). Only `:focus-visible` may draw one,
 * and that is read from the class's own variant prefix, so a `border-2` beside
 * a `focus-visible:ring-2` on the same line still counts, and so does a
 * `not-focus-visible:` one. A zero width (`border-0`, `outline-0`) removes a
 * stroke rather than drawing one, so it is not counted — DESIGN.md's grep
 * matches it, but the grep is the floor of the judgement, not the ceiling.
 *
 * The bare `border` / `ring` / `outline` class is a 1px stroke in Tailwind v4,
 * and so is a bare side (`border-t`, `border-x`, `border-s`, …); the grep
 * could see neither. Both are counted in their important forms too
 * (`!border-t`, `border!`), which are the same stroke with a louder voice. It is read only as a whole class inside a
 * string literal, outside stylesheets: the same word is a CSS property or
 * transition target, an identifier (`const ring = box * 0.42`), and a module
 * path (`'@/lib/lab/outline'`).
 */
const STROKE =
  /(?<![\w-])(?:border(?:-[trblxyse])?-(?!0(?![\d.]))\d+|border-(?:solid|white|black)|ring-(?!0(?![\d.]))\d+|outline-(?!0(?![\d.]))\d+)(?![\w-])/g
const BARE_STROKE = /(?<=[\s"'`:!])(?:border(?:-[trblxyse])?|ring|outline)(?=!?[\s"'`])/g

/** Which characters of `source` sit inside a quoted string (quotes excluded). */
function stringMask(source: string): Uint8Array {
  const mask = new Uint8Array(source.length)
  let quote: string | null = null
  for (let i = 0; i < source.length; i += 1) {
    const char = source[i]
    if (quote === null) {
      if (char === '"' || char === "'" || char === '`') quote = char
    } else if (char === '\\') {
      mask[i] = 1
      if (i + 1 < source.length) mask[i + 1] = 1
      i += 1
    } else if (char === quote || (char === '\n' && quote !== '`')) quote = null
    else mask[i] = 1
  }
  return mask
}
const strokeAccept = (code: string) => (m: RegExpExecArray) => {
  const prefix = classPrefix(code, m.index)
  return !prefix.includes('focus-visible:') || prefix.includes('not-focus-visible:')
}

/**
 * DESIGN.md "Deleted — do not reintroduce". `.glass` the primitive is the bare
 * word; the surviving surface tokens are `glass` behind a hyphen (`btn-glass`,
 * `bg-glass`, `bg-glass-raised`, `--color-glass`), which the guards on the bare
 * word never match. The divider is `.rule` with its dot, as DESIGN.md explains,
 * and not after an identifier (`violation.rule` is a property read).
 */
const DELETED =
  /(?<![\w-])(?:glass-flat|eyebrow|y2k-[\w-]*|holo-[\w-]*|water-[\w-]*|cyber-[\w-]*|animate-radar-[\w-]*|app-glow|rainbow-glow-bar|animate-float-gentle|vfx\.css|glass)(?![\w-])|--font-mono\b|--font-display\b|--color-edge\b|(?<![\w)\]])\.rule(?![\w-])/g
const SURVIVORS = /btn-glass|glass-raised|bg-glass|--color-glass/
/**
 * `glass: 'oklch(…)'` — the surviving token's own key, in the token source
 * only. In a component, `cond({ glass: open })` is the deleted class.
 */
const GLASS_TOKEN_KEY = /^\s*:/
function deletedAccept(code: string, file: string) {
  return (m: RegExpExecArray) => {
    if (m[0] !== 'glass') return true
    if (SURVIVORS.test(lineText(code, m.index))) return false
    const isKey =
      file === TOKEN_SOURCE &&
      code[m.index - 1] !== '.' &&
      GLASS_TOKEN_KEY.test(code.slice(m.index + 5, m.index + 7))
    return !isKey
  }
}

/** Scrollbar CSS anywhere but globals.css (rule 6). The two class names are the sanctioned API. */
const SCROLLBAR = /::-webkit-scrollbar|\bscrollbar(?!-(?:silent|area|table))/g
const SCROLLBAR_FILE = 'src/app/globals.css'

/**
 * An arbitrary pixel value in a class name. The count is the budget. A
 * `text-[10px]` is already `belowFloor`'s and is not counted twice; an
 * off-scale size at or above the floor (`text-[15px]`) is counted here.
 */
const ARBITRARY_PX = /\[(-?\d+(?:\.\d+)?)px\]/g
const arbitraryPxAccept = (code: string) => (m: RegExpExecArray) =>
  !(code.slice(Math.max(0, m.index - 5), m.index) === 'text-' && Number(m[1]) < FLOOR_PX)

/**
 * A duration of its own (D1, 2026-10-23): a `duration-<n>` or `duration-[…]`
 * class in a component, or a `transition` / `animation` with a time in a
 * stylesheet. CLAUDE.md §Motion allows `.animate-fade-in` and the launcher
 * glow, both in globals.css, which is the one file whose transitions and
 * animations are not counted. `duration-(--motion)` reads a token and is not.
 */
const DURATION_CLASS = /(?<![\w-])duration-(?:\d+\b|\[[^\]\s]*\])/g
const RAW_TRANSITION =
  /\b(?:transition|animation)(?:-duration)?\s*:[^;{}]*?(?<![\w-])\d*\.?\d+m?s\b/g

/**
 * Inside `@media (prefers-reduced-motion: reduce)` a duration is the global
 * stillness override CLAUDE.md §Motion describes (`0.01ms !important` in the
 * shared primitives), the opposite of a duration of its own.
 */
const REDUCED_MOTION = /prefers-reduced-motion\s*:\s*reduce\b/g
function insideReducedMotion(code: string, index: number): boolean {
  let media = -1
  REDUCED_MOTION.lastIndex = 0
  for (let m = REDUCED_MOTION.exec(code); m !== null && m.index < index; m = REDUCED_MOTION.exec(code)) {
    media = m.index
  }
  if (media === -1) return false
  const open = code.indexOf('{', media)
  if (open === -1 || open > index) return false
  let depth = 0
  for (let i = open; i < index; i += 1) {
    if (code[i] === '{') depth += 1
    else if (code[i] === '}') depth -= 1
    if (depth === 0) return false
  }
  return true
}

/**
 * A hard corner (DESIGN.md §Surfaces: radii are 12 / 14 / 26 / 32, and a 4px or
 * square corner on a borderless translucent panel reads as a rendering
 * fault). `rounded-none`, side forms included, in any file; a zero
 * `border-radius` (or any `…radius:` property, `--radius: 0` too) in a
 * stylesheet. The lookahead keeps `0.5rem` and `05px` from reading as zero.
 */
const HARD_CORNER_CLASS = /(?<![\w-])rounded(?:-[trblse]{1,2})?-none(?![\w-])/g
const HARD_CORNER_CSS = /\bradius\s*:\s*0(?![.\d])/g

/**
 * A test names what it forbids — `expect(page).not.toContain('eyebrow')`, an
 * `it('puts no eyebrow over …')` title — and puts nothing on a screen, so the
 * seven audit rules do not read test files.
 */
const TEST_FILE = /\.test\.tsx?$/

/** The text of the line holding `index`. */
function lineText(source: string, index: number): string {
  const start = source.lastIndexOf('\n', index - 1) + 1
  const end = source.indexOf('\n', index)
  return source.slice(start, end === -1 ? source.length : end)
}

/** The variant prefix of the class holding `index`: `focus-visible:` in `focus-visible:ring-2`. */
function classPrefix(source: string, index: number): string {
  let start = index
  while (start > 0 && !/[\s"'`{}(),]/.test(source[start - 1])) start -= 1
  return source.slice(start, index)
}

/**
 * The nearest component or function declared above `index`. Good enough to
 * scope an allowlist to one named symbol: a hex after GoogleMark's closing
 * brace sits under the next declaration, not under GoogleMark.
 */
const DECLARATION = /\bfunction\s+([A-Za-z_$][\w$]*)|\b(?:const|let)\s+([A-Za-z_$][\w$]*)\s*=/g
function enclosingName(source: string, index: number): string | undefined {
  DECLARATION.lastIndex = 0
  let name: string | undefined
  let match = DECLARATION.exec(source)
  while (match !== null && match.index < index) {
    name = match[1] ?? match[2]
    match = DECLARATION.exec(source)
  }
  return name
}

function lineOf(source: string, index: number): number {
  let line = 1
  for (let i = 0; i < index; i += 1) if (source[i] === '\n') line += 1
  return line
}

function collect(
  source: string,
  file: string,
  pattern: RegExp,
  rule: Rule,
  accept: (match: RegExpExecArray) => boolean = () => true,
): Violation[] {
  const found: Violation[] = []
  // Fresh lastIndex per call: these are module-level /g regexes and a shared
  // one silently skips matches on the second file it sees.
  pattern.lastIndex = 0
  let match = pattern.exec(source)
  while (match !== null) {
    if (accept(match)) {
      found.push({ file, line: lineOf(source, match.index), rule, text: match[0] })
    }
    match = pattern.exec(source)
  }
  return found
}

/**
 * Blanks the prose value of a `comment:` property in the token source — its
 * `TokenGroup.comment`, emitted as a CSS comment into theme.css — including
 * its `'…' +` continuations. It is documentation by name, and it is where the
 * token source explains the very sizes, families and names these rules ban:
 * `text-[9px]`, `--font-mono`, "the three glass layers".
 *
 * Only in that file, and only after `stripComments`: the string body may cross
 * newlines, so anywhere else a `comment: '` (in a `//` remark, or a
 * component's own object key) would blank real code for every rule.
 */
const TOKEN_SOURCE = 'packages/colorlab-tokens/src/tokens.ts'
const COMMENT_PROPERTY = /\bcomment\s*:\s*((?:(['"`])(?:\\.|(?!\2)[^\\])*\2\s*\+?\s*)+)/g
function stripCommentProperties(source: string): string {
  return source.replace(COMMENT_PROPERTY, (whole: string, value: string) =>
    whole.slice(0, whole.length - value.length) + value.replace(/[^\n]/g, ' '),
  )
}

/**
 * Blanks out comment bodies, preserving newlines so every reported line number
 * still points at the right line.
 *
 * A guard that fires on its own documentation gets muted, not obeyed — the same
 * lesson `token-drift.test.ts` records, where a scan of the token source failed
 * on `#040406` written inside a `comment:` string describing the page
 * background. Without this, the three files that *explain* these rules were the
 * last three files reported as breaking them: tokens.ts naming `text-[9px]`,
 * `text-[10px]` and `text-[0.65rem]` in the sentence saying they fail the
 * build; globals.css saying what replaced `--font-mono`; and color.ts recording
 * that `text-amber-400` and `text-emerald-400` were deleted.
 *
 * Strings are deliberately NOT stripped. A Tailwind class always lives in one,
 * so stripping them would blind the scanner to every real violation. They are
 * still tracked, because a comment opener inside one is not a comment: a regex
 * strip read `accept="image/*"` as one and blanked the code up to the next
 * close — the very strings the scanner exists to read. A quoted string ends at
 * a newline, so a stray apostrophe (JSX text, a regex literal) costs at most
 * the rest of its line, and only ever as an over-report.
 *
 * A `//` right after `:` is a URL scheme, not a comment.
 */
function stripComments(source: string): string {
  const out = source.split('')
  const blank = (from: number, to: number) => {
    for (let i = from; i < to; i += 1) if (out[i] !== '\n') out[i] = ' '
  }
  let quote: string | null = null
  let i = 0
  while (i < source.length) {
    const char = source[i]
    if (quote !== null) {
      if (char === '\\') i += 2
      else {
        if (char === quote || (char === '\n' && quote !== '`')) quote = null
        i += 1
      }
      continue
    }
    if (char === '"' || char === "'" || char === '`') {
      quote = char
      i += 1
    } else if (char === '/' && source[i + 1] === '*') {
      const close = source.indexOf('*/', i + 2)
      const end = close === -1 ? source.length : close + 2
      blank(i, end)
      i = end
    } else if (char === '/' && source[i + 1] === '/' && source[i - 1] !== ':') {
      const newline = source.indexOf('\n', i)
      const end = newline === -1 ? source.length : newline
      blank(i, end)
      i = end
    } else i += 1
  }
  return out.join('')
}

export function scanSource(source: string, file: string): Violation[] {
  const underFloor = (match: RegExpExecArray) => toPx(match[1], match[2]) < FLOOR_PX
  const uncommented = stripComments(source)
  const code = file === TOKEN_SOURCE ? stripCommentProperties(uncommented) : uncommented

  return [
    ...collect(code, file, TAILWIND_NAMED_BELOW_FLOOR, 'belowFloor'),
    ...collect(code, file, ARBITRARY_SIZE, 'belowFloor', underFloor),
    ...collect(code, file, CSS_FONT_SIZE, 'belowFloor', underFloor),
    ...collect(code, file, CSS_FONT_SHORTHAND, 'belowFloor', underFloor),
    ...collect(code, file, JSX_FONT_SIZE, 'belowFloor', underFloor),
    ...collect(code, file, MONO, 'mono'),
    ...collect(code, file, PALETTE, 'palette'),
    ...(TEST_FILE.test(file) ? [] : auditRules(code, file)),
  ].sort((a, b) => a.line - b.line)
}

/** Tailwind v4's bare stroke classes, read only inside a string. */
function bareStrokes(code: string, file: string): Violation[] {
  const inString = stringMask(code)
  const accept = strokeAccept(code)
  return collect(code, file, BARE_STROKE, 'stroke', (m) => inString[m.index] === 1 && accept(m))
}

/** The seven rules that were DESIGN.md's audit greps. */
function auditRules(code: string, file: string): Violation[] {
  return [
    ...(HEX_SCOPE.test(file) && !HEX_FILES.test(file)
      ? collect(code, file, HEX, 'hex', (m) => {
          if (HEX_LINE.test(lineText(code, m.index))) return false
          const owner = enclosingName(code, m.index)
          return owner === undefined || !HEX_COMPONENTS.has(owner)
        })
      : []),
    ...collect(code, file, STROKE, 'stroke', strokeAccept(code)),
    ...(file.endsWith('.css') ? [] : bareStrokes(code, file)),
    ...collect(code, file, DELETED, 'deletedVocab', deletedAccept(code, file)),
    ...(file === SCROLLBAR_FILE ? [] : collect(code, file, SCROLLBAR, 'scrollbarCss')),
    ...(file.endsWith('.tsx') ? collect(code, file, ARBITRARY_PX, 'arbitraryPx', arbitraryPxAccept(code)) : []),
    ...(file.endsWith('.tsx') ? collect(code, file, DURATION_CLASS, 'duration') : []),
    ...(file.endsWith('.css') && file !== SCROLLBAR_FILE
      ? collect(code, file, RAW_TRANSITION, 'duration', (m) => !insideReducedMotion(code, m.index))
      : []),
    ...collect(code, file, HARD_CORNER_CLASS, 'hardCorner'),
    ...(file.endsWith('.css') ? collect(code, file, HARD_CORNER_CSS, 'hardCorner') : []),
  ]
}

export function scanRepo(): Violation[] {
  return sourceFiles().flatMap((file) =>
    scanSource(readFileSync(join(REPO_ROOT, file), 'utf8'), file),
  )
}

/** Per-file counts, omitting clean files so the baseline shrinks as work lands. */
function zero(): Record<Rule, number> {
  return Object.fromEntries(RULES.map((rule) => [rule, 0])) as Record<Rule, number>
}

export function tally(violations: readonly Violation[]): Baseline {
  const baseline: Record<string, Record<Rule, number>> = {}
  for (const violation of violations) {
    baseline[violation.file] ??= zero()
    baseline[violation.file][violation.rule] += 1
  }
  return Object.fromEntries(Object.entries(baseline).sort(([a], [b]) => a.localeCompare(b)))
}

export function totals(baseline: Baseline): Counts {
  const sum = zero()
  for (const counts of Object.values(baseline)) {
    // `?? 0`: a baseline written before a rule existed has no key for it.
    for (const rule of RULES) sum[rule] += counts[rule] ?? 0
  }
  return sum
}
